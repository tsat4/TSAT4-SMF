-- เลิกใช้ (2026-10-25): ตารางกิจกรรมย้ายไป Tx Data ชื่อ mt_<กิจกรรม>_* / tx_<กิจกรรม>_* ดู db/act/ และ scripts/act-sql.js · ล้างของเก่าด้วย db/07_drop_act_from_mx.sql
-- Schedule Plan ของระบบกิจกรรม (5S, SAFETY, QCC ฯลฯ) รันใน MX ครั้งเดียว (รันซ้ำได้)
-- mt_act_user   สมาชิกและบทบาทของระบบกิจกรรม (viewer / user / admin) ใช้คอลัมน์เดียวกับ mt_sto_user
-- mt_act_owner  หน่วยงานผู้ดูแลกิจกรรมในแต่ละปี เช่น (2026, '5s', 'STO') เปลี่ยนได้ทุกปีตามนโยบาย
-- mt_act_plan   รายการในแผน (1 แถว = กิจกรรมหรือนัดหมาย มีวันเริ่มและวันจบ)
-- สิทธิ์: ทุกคนที่ login ดูได้ ส่วนการแก้ไขทำได้เฉพาะ admin ใน mt_act_user ที่หน่วยงานตรงกับผู้ดูแลของปีนั้น (และ creator)
-- ชื่อกิจกรรมใช้ id ตามเมนู: 100p, 5s, cfo, e-day, kaizen, lean, qcc, safety, smf

create table if not exists public.mt_act_user (
  employee_id text primary key references public.mt_main_user (employee_id),
  department text not null,
  role text not null check (role in ('viewer', 'user', 'admin')),
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

create table if not exists public.mt_act_owner (
  year integer not null check (year between 2000 and 2100),
  activity text not null,
  department text not null,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  primary key (year, activity)
);

create table if not exists public.mt_act_plan (
  id bigint generated by default as identity primary key,
  activity text not null,
  title text not null,
  detail text,
  start_date date not null,
  end_date date not null,
  responsible text,
  status text not null default 'planned' check (status in ('planned', 'done', 'cancelled')),
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_act_plan_dates check (end_date >= start_date)
);

create index if not exists mt_act_plan_activity_dates on public.mt_act_plan (activity, start_date, end_date);

-- server ใช้ service key ซึ่งข้าม RLS ได้ เปิด RLS ไว้เพื่อกันการเข้าถึงด้วย anon key
alter table public.mt_act_user enable row level security;
alter table public.mt_act_owner enable row level security;
alter table public.mt_act_plan enable row level security;
