-- ===== 5s: team, settings, yearly plan (Gantt) =====

-- ทีมรายปี: admin = ดูแล Setting, chairman = หัวหน้าทีมตรวจ, auditor = ผู้ตรวจในทีม A–Z
create table if not exists public.mt_5s_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null check (role in ('admin', 'chairman', 'auditor')),
  team text check (team ~ '^[A-Z]$'),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_5s_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_5s_team_unique unique nulls not distinct (year, employee_id, role, team)
);
create index if not exists mt_5s_team_lookup on public.mt_5s_team (year, employee_id);

create table if not exists public.mt_5s_setting (
  key text primary key,
  value text not null
);

-- แผนประจำปีแบบ Gantt (รายการชื่อเดียวกันอยู่แถวเดียวกัน) และปฏิทินรวม
create table if not exists public.mt_5s_plan (
  id bigint generated by default as identity primary key,
  title text not null,
  detail text,
  start_date date not null,
  end_date date not null,
  responsible text,
  status text not null default 'planned' check (status in ('planned', 'done', 'cancelled')),
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_5s_plan_dates check (end_date >= start_date)
);
create index if not exists mt_5s_plan_dates on public.mt_5s_plan (start_date, end_date);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_5s · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_5s', 'img_5s', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;

-- ===== 5s: checklist audit =====

create table if not exists public.mt_5s_area (
  id bigint generated by default as identity primary key,
  code text not null unique,                              -- เช่น A01
  area_type text not null check (area_type in ('โรงงาน', 'สำนักงาน')),
  name text not null,
  section text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- เจ้าของพื้นที่: ปีละ 1 คนต่อพื้นที่ 1 คนดูแลได้หลายพื้นที่
create table if not exists public.mt_5s_area_owner (
  year integer not null check (year between 2000 and 2100),
  area_id bigint not null references public.mt_5s_area (id) on delete cascade,
  employee_id text not null,
  primary key (year, area_id)
);
create index if not exists mt_5s_area_owner_employee on public.mt_5s_area_owner (year, employee_id);

-- หัวข้อตรวจรายปี (5S: 25 ข้อ, s_group 1–5)
create table if not exists public.mt_5s_checklist (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  item_no integer not null check (item_no between 1 and 200),
  s_group integer not null check (s_group between 1 and 20),
  title text not null,
  score_max integer not null default 5 check (score_max > 0),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (year, item_no)
);

-- แผนตรวจ Committee: พื้นที่ × เดือน × สัปดาห์ (W1 = 1–7, W2 = 8–14, W3 = 15–21, W4 = 22–สิ้นเดือน)
create table if not exists public.mt_5s_audit_plan (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  area_id bigint not null references public.mt_5s_area (id) on delete cascade,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 4),
  round integer check (round between 1 and 6),
  team text check (team ~ '^[A-Z]$'),
  created_at timestamptz not null default now(),
  unique (year, area_id, month, week)
);

insert into public.mt_5s_setting (key, value) values
  ('pass_percent', '80'),                -- ผ่านเมื่อ % ≥ 80
  ('issue_score', '3'),                  -- Committee: ข้อที่ได้ ≤ 3 ต้องเปิด Issue
  ('issue_due_days_before_next', '10'),  -- แก้ให้เสร็จก่อนตรวจรอบถัดไป 10 วัน
  ('issue_photo_max', '1'),              -- รูปปัญหา 16:9 1 รูป
  ('self_audit_due_day', '10')           -- Self Audit ภายในวันที่ 10 ของเดือน
on conflict (key) do nothing;

create table if not exists public.tx_5s_audit (
  id bigint generated by default as identity primary key,
  audit_no text not null unique,                          -- C|S-<area>-<ddMMyy>-<seq> เช่น C-A01-040926-01
  year integer not null check (year between 2000 and 2100),
  audit_type text not null check (audit_type in ('SELF', 'COMMITTEE')),
  area_id bigint not null references public.mt_5s_area (id),
  plan_id bigint references public.mt_5s_audit_plan (id) on delete set null,
  team text,
  audited_at timestamptz not null,
  total_score numeric(8, 2) not null default 0,
  percent_score numeric(5, 2) not null default 0,
  result text check (result in ('PASS', 'NEED_IMPROVE')),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'COMPLETED')),
  created_by text,
  created_at timestamptz not null default now()
);
create index if not exists tx_5s_audit_lookup on public.tx_5s_audit (year, area_id, audited_at);

create table if not exists public.tx_5s_audit_score (
  audit_id bigint not null references public.tx_5s_audit (id) on delete cascade,
  checklist_id bigint not null references public.mt_5s_checklist (id),
  score numeric(5, 2) not null check (score >= 0),       -- 0 = Issue เดิมไม่มี Action
  primary key (audit_id, checklist_id)
);

-- คนในใบตรวจ: assigned = ได้รับมอบหมาย, participated = ไปตรวจจริง, receiver = ผู้รับตรวจในพื้นที่
create table if not exists public.tx_5s_audit_person (
  audit_id bigint not null references public.tx_5s_audit (id) on delete cascade,
  employee_id text not null,
  kind text not null check (kind in ('assigned', 'participated', 'receiver')),
  primary key (audit_id, employee_id, kind)
);

create table if not exists public.tx_5s_issue (
  id bigint generated by default as identity primary key,
  issue_no text not null unique,                          -- ISS0001
  audit_id bigint not null references public.tx_5s_audit (id) on delete cascade,
  area_id bigint not null references public.mt_5s_area (id),
  checklist_id bigint not null references public.mt_5s_checklist (id),
  score numeric(5, 2) not null,
  description text not null,
  issue_date date not null,
  responsible_id text,
  due_date date,                                          -- null = รอกำหนดรอบถัดไป
  action_description text,
  action_date date,
  status text not null default 'OPEN' check (status in ('OPEN', 'ON_PLAN', 'WAIT_VERIFY', 'OVERDUE', 'CLOSED')),
  verify_audit_no text,                                   -- ใบตรวจรอบถัดไปที่ยืนยันผล (ข้อมูลเดิมบางใบไม่มีในระบบ จึงเก็บเป็นเลข)
  final_score numeric(5, 2),
  closed_by text,
  closed_at date
);
create index if not exists tx_5s_issue_area on public.tx_5s_issue (area_id, status);

create table if not exists public.tx_5s_issue_photo (
  id bigint generated by default as identity primary key,
  issue_id bigint not null references public.tx_5s_issue (id) on delete cascade,
  kind text not null check (kind in ('BEFORE', 'AFTER')),
  url text not null,
  created_at timestamptz not null default now(),
  unique (issue_id, url)
);

-- % ของแต่ละหมวดต่อใบตรวจ (Summary / Ranking) · security_invoker = ใช้สิทธิ์ของคนเรียก ไม่ข้าม RLS
create or replace view public.v_5s_audit_group with (security_invoker = true) as
select s.audit_id, c.s_group,
  sum(s.score) as score,
  sum(c.score_max) as score_max,
  round(sum(s.score) * 100.0 / nullif(sum(c.score_max), 0), 2) as percent
from public.tx_5s_audit_score s
join public.mt_5s_checklist c on c.id = s.checklist_id
group by s.audit_id, c.s_group;

