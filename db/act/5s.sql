-- ===== 5s: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_5s_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_5s_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_5s_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_5s_team add column if not exists department text;
alter table public.mt_5s_team
  drop constraint if exists mt_5s_team_role_check,
  add constraint mt_5s_team_role_check check (role in ('admin', 'chairman', 'vice', 'advisor', 'auditor', 'owner', 'member')),
  drop constraint if exists mt_5s_team_member_has_dept,
  add constraint mt_5s_team_member_has_dept check ((role = 'member') = (department is not null)),
  drop constraint if exists mt_5s_team_unique,
  add constraint mt_5s_team_unique unique nulls not distinct (year, employee_id, role, team, area_id, department);
create index if not exists mt_5s_team_lookup on public.mt_5s_team (year, employee_id);
create unique index if not exists mt_5s_team_one_owner on public.mt_5s_team (year, area_id) where role = 'owner';

create table if not exists public.mt_5s_setting (
  key text primary key,
  value text not null
);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_5s · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_5s', 'img_5s', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;

-- ===== 5s: Project Planner =====

-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_5s_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_5s_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p12
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_5s_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_5s_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_5s_task_year on public.mt_5s_task (year, parent_id, sort_no);
-- วันที่ทำครบ 100% (server ใส่ให้) ใช้บอกเสร็จก่อนแผน / ตามแผน / ช้า เทียบกับ end_date · เพิ่มทีหลัง จึงใช้ add column (รันซ้ำได้)
alter table public.mt_5s_task add column if not exists done_on date;

-- ===== 5s: checklist audit =====

create table if not exists public.mt_5s_area (
  id bigint generated by default as identity primary key,
  code text not null unique,                              -- เช่น A01
  area_type text not null check (area_type in ('โรงงาน', 'สำนักงาน')),
  name text not null,
  section text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- เจ้าของพื้นที่อยู่ใน mt_5s_team (role owner) ผูก area_id กับพื้นที่ที่นี่
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'mt_5s_team_area_fk') then
    alter table public.mt_5s_team add constraint mt_5s_team_area_fk foreign key (area_id) references public.mt_5s_area (id) on delete cascade;
  end if;
end $$;

-- หัวข้อตรวจรายปี (5S: 25 ข้อ, s_group 1–5)
create table if not exists public.mt_5s_checklist (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  item_no integer not null check (item_no between 1 and 200),
  s_group integer not null check (s_group between 1 and 20),
  title text not null,
  score_max integer not null default 5 check (score_max > 0),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (year, item_no)
);

-- แผนตรวจ Committee: พื้นที่ × เดือน × สัปดาห์ (W1 = 1–7, W2 = 8–14, W3 = 15–21, W4 = 22–สิ้นเดือน)
create table if not exists public.mt_5s_audit_plan (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  area_id bigint not null references public.mt_5s_area (id) on delete cascade,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 4),
  round integer check (round between 1 and 6),
  team text check (team ~ '^[A-Z]$'),
  created_at timestamptz not null default now(),
  unique (year, area_id, month, week)
);

insert into public.mt_5s_setting (key, value) values
