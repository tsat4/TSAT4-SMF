-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_5s_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_5s_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p5
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_5s_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_5s_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_5s_task_year on public.mt_5s_task (year, parent_id, sort_no);
-- วันที่ทำครบ 100% (server ใส่ให้) ใช้บอกเสร็จก่อนแผน / ตามแผน / ช้า เทียบกับ end_date · เพิ่มทีหลัง จึงใช้ add column (รันซ้ำได้)
alter table public.mt_5s_task add column if not exists done_on date;

do $$ begin
  if to_regclass('public.mt_5s_plan') is not null and not exists (select 1 from public.mt_5s_task) then
    with g as (
      select extract(year from start_date)::int as year, title, count(*) as n, min(start_date) as first_start,
        min(start_date) as start_date, max(end_date) as end_date,
        bool_and(status = 'done') as done, min(created_by) as created_by, max(responsible) as responsible, max(detail) as detail
      from public.mt_5s_plan where status <> 'cancelled'
      group by 1, 2
    )
    insert into public.mt_5s_task (year, sort_no, title, start_date, end_date, progress, note, created_by)
    select year, row_number() over (partition by year order by first_start, title), title,
      case when n = 1 then start_date end, case when n = 1 then end_date end,
      case when n = 1 and done then 100 else 0 end,
      case when n = 1 then nullif(concat_ws(' · ', detail, 'ผู้รับผิดชอบ: ' || responsible), '') end,
      coalesce(created_by, 'import')
    from g;

    insert into public.mt_5s_task (year, parent_id, sort_no, title, start_date, end_date, progress, note, created_by)
    select t.year, t.id, row_number() over (partition by t.id order by p.start_date, p.id), p.title, p.start_date, p.end_date,
      case when p.status = 'done' then 100 else 0 end,
      nullif(concat_ws(' · ', p.detail, 'ผู้รับผิดชอบ: ' || p.responsible), ''), p.created_by
    from public.mt_5s_plan p
    join public.mt_5s_task t on t.parent_id is null and t.title = p.title and t.year = extract(year from p.start_date)::int and t.start_date is null
    where p.status <> 'cancelled';
  end if;
end $$;

alter table public.mt_5s_task enable row level security;

-- ตรวจ: main / sub = ข้อหลัก / ข้อรองใน Planner (เทียบกับแผนเดิมใน mt_5s_plan ที่ไม่ได้ยกเลิก)
select (select count(*) from public.mt_5s_task where parent_id is null) as main,
  (select count(*) from public.mt_5s_task where parent_id is not null) as sub;

