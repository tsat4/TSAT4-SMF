-- ===== cfo: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_cfo_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_cfo_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_cfo_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_cfo_team add column if not exists department text;
alter table public.mt_cfo_team
  drop constraint if exists mt_cfo_team_role_check,
  add constraint mt_cfo_team_role_check check (role in ('admin', 'chairman', 'vice', 'auditor', 'owner', 'member')),
  drop constraint if exists mt_cfo_team_member_has_dept,
  add constraint mt_cfo_team_member_has_dept check ((role = 'member') = (department is not null)),
  drop constraint if exists mt_cfo_team_unique,
  add constraint mt_cfo_team_unique unique nulls not distinct (year, employee_id, role, team, area_id, department);
create index if not exists mt_cfo_team_lookup on public.mt_cfo_team (year, employee_id);
create unique index if not exists mt_cfo_team_one_owner on public.mt_cfo_team (year, area_id) where role = 'owner';

create table if not exists public.mt_cfo_setting (
  key text primary key,
  value text not null
);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_cfo · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_cfo', 'img_cfo', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;

-- ===== cfo: Project Planner =====

-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_cfo_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_cfo_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p5
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_cfo_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_cfo_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_cfo_task_year on public.mt_cfo_task (year, parent_id, sort_no);

-- ===== cfo: Carbon Footprint for Organization =====

-- หมวดการปล่อย 23 หมวด (Scope 1: 1-1…1-4, Scope 2: 2-1…2-4, Scope 3: 3-1…3-15)
create table if not exists public.mt_cfo_scope (
  code text primary key check (code ~ '^[1-3]-[0-9]{1,2}$'),
  scope smallint not null check (scope between 1 and 3),
  name text not null,
  name_th text
);

-- ค่า GWP ต่อก๊าซ (เช่น AR5) ใช้คูณ kg ก๊าซ -> kgCO2e
create table if not exists public.mt_cfo_gwp (
  code text primary key,                                  -- AR5
  co2 numeric not null default 1,
  ch4_fossil numeric not null default 0,
  ch4 numeric not null default 0,
  n2o numeric not null default 0,
  sf6 numeric not null default 0,
  nf3 numeric not null default 0,
  reference text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- Emission factor ทุก Scope ในตารางเดียว · kgco2e = ต่อ 1 หน่วย (รวมทุกก๊าซ) · ค่าแยกก๊าซมีเฉพาะ Scope 1
-- ค่าที่ถูกใช้แล้วห้ามแก้ ถ้าค่าเปลี่ยนให้เพิ่มแถวใหม่แล้วปิดแถวเดิม (Inactive) ผลย้อนหลังจะไม่เปลี่ยน
create table if not exists public.mt_cfo_ef (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (sc1021026-091)
  scope_code text not null references public.mt_cfo_scope (code),
  kind text,                                              -- On-Road / Off-Road หรือกลุ่มของ Scope 3
  name text not null,
  detail text,
  unit text not null,
  kgco2e numeric check (kgco2e >= 0),                     -- ว่าง = ยังไม่มีค่า ใช้บันทึกไม่ได้
  co2 numeric, ch4_fossil numeric, ch4 numeric, n2o numeric, hfc numeric, pfc numeric,
  reference text,
  year integer,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);
create index if not exists mt_cfo_ef_scope on public.mt_cfo_ef (scope_code, status);

-- กิจกรรมที่ต้องเก็บข้อมูลทุกเดือน (รถผู้บริหาร, Forklift, ไฟฟ้า ...) ของหน่วยงานไหน ใช้ EF ตัวไหน
create table if not exists public.mt_cfo_activity (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (ac1051026-001)
  ef_id bigint not null references public.mt_cfo_ef (id),
  gwp_code text not null references public.mt_cfo_gwp (code),
  department text not null,
  name text not null,
  detail text,
  calc text check (calc in ('septic')),                   -- ปริมาณคำนวณจากสูตร (septic = บ่อเกรอะ ค่าตั้งต้นใน mt_cfo_setting)
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- ข้อมูลรายเดือน 1 แถว = 1 กิจกรรม × 1 เดือน · ef_id / gwp_code = ค่าที่ใช้ตอนบันทึก (คัดลอกจากกิจกรรม)
create table if not exists public.tx_cfo_entry (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.mt_cfo_activity (id),
  month date not null check (extract(day from month) = 1),
  qty numeric not null check (qty >= 0),
  ef_id bigint not null references public.mt_cfo_ef (id),
  gwp_code text not null references public.mt_cfo_gwp (code),
  inputs jsonb,                                           -- ค่าที่กรอกให้สูตร calc เช่น {"people": 250, "days": 26}
  doc text,                                               -- ลิงก์เอกสาร/รูปหลักฐาน (bucket img_cfo)
  status text not null default 'DRAFT' check (status in ('DRAFT', 'CONFIRMED')),
  remark text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text,
  updated_at timestamptz,
  unique (activity_id, month)
);
create index if not exists tx_cfo_entry_month on public.tx_cfo_entry (month);

-- ค่าตั้งต้นบ่อเกรอะ (IPCC): kg CH4 = คน × วัน × BOD × 0.001 × B0 × MCF × I · เป้าลด
insert into public.mt_cfo_setting (key, value) values
  ('septic_bod', '40'), ('septic_b0', '0.6'), ('septic_mcf', '0.5'), ('septic_i', '1'),
  ('target_percent', '5')                 -- เป้าลดจากปีฐาน (%) ค่าเดิมของ TSATP4-CFO
on conflict (key) do nothing;

-- ผลต่อแถว: tCO2e = qty × kgco2e / 1000 · แยกก๊าซ (Scope 1) = qty × EF ก๊าซ × GWP / 1000
-- บ่อเกรอะ (calc = septic): qty = kg CH4 → tCO2e = qty × GWP CH4 ของรายการ / 1000 (เหมือน TSATP4-CFO saveSepticTx_)
create or replace view public.v_cfo_entry with (security_invoker = true) as
select e.id, e.month, e.status, a.department, a.name as activity, a.detail, s.scope, s.code as scope_code, s.name as scope_name,
  f.name as source, f.unit, e.qty, f.kgco2e,
  round(e.qty * case when a.calc = 'septic' then g.ch4 else f.kgco2e end / 1000, 6) as tco2e,
  round(e.qty * coalesce(f.co2, 0) * g.co2 / 1000, 6) as tco2e_co2,
  round(e.qty * (coalesce(f.ch4_fossil, 0) * g.ch4_fossil + case when a.calc = 'septic' then 1 else coalesce(f.ch4, 0) end * g.ch4) / 1000, 6) as tco2e_ch4,
  round(e.qty * coalesce(f.n2o, 0) * g.n2o / 1000, 6) as tco2e_n2o,
  round(e.qty * (coalesce(f.hfc, 0) + coalesce(f.pfc, 0)) / 1000, 6) as tco2e_fgas,
  e.activity_id                                           -- เพิ่มท้ายสุด: create or replace view เพิ่มคอลัมน์ได้แค่ต่อท้าย
from public.tx_cfo_entry e
join public.mt_cfo_activity a on a.id = e.activity_id
join public.mt_cfo_ef f on f.id = e.ef_id
join public.mt_cfo_scope s on s.code = f.scope_code
join public.mt_cfo_gwp g on g.code = e.gwp_code;

-- รวมรายเดือนต่อ Scope (Dashboard)
create or replace view public.v_cfo_month with (security_invoker = true) as
select month, scope, round(sum(tco2e), 6) as tco2e, count(*) as entries
from public.v_cfo_entry
group by month, scope;

