  end if;
end $$;

-- ===== cfo: Carbon Footprint for Organization =====

-- หมวดการปล่อย 23 หมวด (Scope 1: 1-1…1-4, Scope 2: 2-1…2-4, Scope 3: 3-1…3-15)
create table if not exists public.mt_cfo_scope (
  code text primary key check (code ~ '^[1-3]-[0-9]{1,2}$'),
  scope smallint not null check (scope between 1 and 3),
  name text not null,
  name_th text
);

-- ค่า GWP ต่อก๊าซ (เช่น AR5) ใช้คูณ kg ก๊าซ -> kgCO2e
create table if not exists public.mt_cfo_gwp (
  code text primary key,                                  -- AR5
  co2 numeric not null default 1,
  ch4_fossil numeric not null default 0,
  ch4 numeric not null default 0,
  n2o numeric not null default 0,
  sf6 numeric not null default 0,
  nf3 numeric not null default 0,
  reference text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- Emission factor ทุก Scope ในตารางเดียว · kgco2e = ต่อ 1 หน่วย (รวมทุกก๊าซ) · ค่าแยกก๊าซมีเฉพาะ Scope 1
-- ค่าที่ถูกใช้แล้วห้ามแก้ ถ้าค่าเปลี่ยนให้เพิ่มแถวใหม่แล้วปิดแถวเดิม (Inactive) ผลย้อนหลังจะไม่เปลี่ยน
create table if not exists public.mt_cfo_ef (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (sc1021026-091)
  scope_code text not null references public.mt_cfo_scope (code),
  kind text,                                              -- On-Road / Off-Road หรือกลุ่มของ Scope 3
  name text not null,
  detail text,
  unit text not null,
  kgco2e numeric check (kgco2e >= 0),                     -- ว่าง = ยังไม่มีค่า ใช้บันทึกไม่ได้
  co2 numeric, ch4_fossil numeric, ch4 numeric, n2o numeric, hfc numeric, pfc numeric,
  reference text,
  year integer,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);
create index if not exists mt_cfo_ef_scope on public.mt_cfo_ef (scope_code, status);

-- คอลัมน์ตามแบบฟอร์ม TGO Fr-04.1 (บัญชีรายการก๊าซเรือนกระจก) · เพิ่มทีหลัง จึงใช้ add column (รันซ้ำได้)
-- hfc / pfc: kg ต่อหน่วย × GWP ของสารนั้น (ว่าง = ค่าเป็น kgCO2e อยู่แล้ว ใช้ GWP 1) · other = GHG นอกข้อกำหนด (เช่น R-22) × other_gwp
-- separate = การปล่อย GHG โดยตรงที่ทำการรายงานแยก (ไม่รวมในยอด Scope) · source_type = ที่มาข้อมูล (1st / 2nd / Other)
alter table public.mt_cfo_ef
  add column if not exists sf6 numeric, add column if not exists nf3 numeric,
  add column if not exists hfc_gwp numeric, add column if not exists pfc_gwp numeric,
  add column if not exists other numeric, add column if not exists other_gwp numeric,
  add column if not exists separate boolean not null default false,
  add column if not exists source_type text, add column if not exists substitute text,
  add column if not exists co2_bio numeric;              -- CO2 ชีวมวล kg/หน่วย (B7 / E10 / ฟืน ...) รายงานแยก ไม่รวมใน kgco2e (แบบ EF TGO AR5 V2)
alter table public.mt_cfo_ef drop constraint if exists mt_cfo_ef_source_type;
alter table public.mt_cfo_ef add constraint mt_cfo_ef_source_type
  check (source_type in ('self', 'supplier', 'th_lci', 'tgo', 'thai_res', 'int_db', 'other'));

-- กิจกรรมที่ต้องเก็บข้อมูลทุกเดือน (รถผู้บริหาร, Forklift, ไฟฟ้า ...) ของหน่วยงานไหน ใช้ EF ตัวไหน
create table if not exists public.mt_cfo_activity (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (ac1051026-001)
  ef_id bigint not null references public.mt_cfo_ef (id),
  gwp_code text not null references public.mt_cfo_gwp (code),
  department text not null,
  name text not null,
  detail text,
  calc text,                                              -- สูตรปริมาณ (server CFO_CALCS): septic / tkm / km_fuel · ว่าง = กรอกเอง
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);
-- septic = บ่อเกรอะ (คน × วัน → kg CH4) · tkm = ขนส่ง (ตัน × กม.) · km_fuel = ระยะทาง ÷ กม./ลิตร → ลิตร
alter table public.mt_cfo_activity drop constraint if exists mt_cfo_activity_calc_check;
alter table public.mt_cfo_activity add constraint mt_cfo_activity_calc_check check (calc in ('septic', 'tkm', 'km_fuel'));

-- ข้อมูลรายเดือน 1 แถว = 1 กิจกรรม × 1 เดือน · ef_id / gwp_code = ค่าที่ใช้ตอนบันทึก (คัดลอกจากกิจกรรม)
create table if not exists public.tx_cfo_entry (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.mt_cfo_activity (id),
  month date not null check (extract(day from month) = 1),
  qty numeric not null check (qty >= 0),
  ef_id bigint not null references public.mt_cfo_ef (id),
  gwp_code text not null references public.mt_cfo_gwp (code),
  inputs jsonb,                                           -- ค่าที่กรอกให้สูตร calc เช่น {"people": 250, "days": 26}
  doc text,                                               -- ลิงก์เอกสาร/รูปหลักฐาน (bucket img_cfo)
  status text not null default 'DRAFT' check (status in ('DRAFT', 'CONFIRMED')),
  remark text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text,
  updated_at timestamptz,
  unique (activity_id, month)
);
create index if not exists tx_cfo_entry_month on public.tx_cfo_entry (month);

-- TGO Fr-03.2 ประเมินความมีนัยสำคัญ Scope 3: 1 แถว = ปี × หมวด 3-1…3-15 · เกณฑ์ 6 ข้อเป็นคะแนน % (เช่น 5.00) ตามไฟล์ผู้ใช้
-- มีนัยสำคัญ = มีแหล่งปล่อย และมีคะแนนอย่างน้อย 1 เกณฑ์ (คำนวณตอนแสดง ไม่เก็บ)
create table if not exists public.mt_cfo_s3_assess (
  year integer not null check (year between 2000 and 2100),
  scope_code text not null references public.mt_cfo_scope (code) check (scope_code like '3-%'),
  has_source boolean not null default true,
  magnitude numeric(6, 2) not null default 0,
  influence numeric(6, 2) not null default 0,
  risk numeric(6, 2) not null default 0,
  sector numeric(6, 2) not null default 0,
  outsourcing numeric(6, 2) not null default 0,
  engagement numeric(6, 2) not null default 0,
  remark text,
  updated_by text,
  updated_at timestamptz,
  primary key (year, scope_code)
);

-- ฐานที่สร้างตอนเกณฑ์ยังเป็น ✓ / × (boolean): เปลี่ยนเป็นคะแนน % · ✓ = 1.00, × = 0 (รันซ้ำได้)
do $$ declare c text; begin
  foreach c in array array['magnitude', 'influence', 'risk', 'sector', 'outsourcing', 'engagement'] loop
    if (select data_type from information_schema.columns where table_schema = 'public' and table_name = 'mt_cfo_s3_assess' and column_name = c) = 'boolean' then
      execute format('alter table public.mt_cfo_s3_assess alter column %I drop default, alter column %I type numeric(6, 2) using (case when %I then 1 else 0 end), alter column %I set default 0', c, c, c, c);
    end if;
  end loop;
end $$;

-- บันทึกการปรับปรุง (ฟอร์ม TGO): server เขียนให้เองเมื่อผู้จัดทำแก้ master / ค่าตั้งต้น / ยืนยันเดือน · เพิ่มเองได้ ไม่มีการลบ
create table if not exists public.tx_cfo_revision (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  area text not null,                                     -- ส่วนที่แก้ (EF, กิจกรรม, ตั้งค่า, ยืนยันเดือน, Fr-03.2 ...)
  ref text,                                               -- ตำแหน่ง (รหัส / ชื่อรายการ)
  detail text not null,
  by text not null
);
create index if not exists tx_cfo_revision_at on public.tx_cfo_revision (at desc);

-- ค่าตั้งต้นบ่อเกรอะ (IPCC): kg CH4 = คน × วัน × BOD × 0.001 × B0 × MCF × I · เป้าลด
insert into public.mt_cfo_setting (key, value) values
  ('septic_bod', '40'), ('septic_b0', '0.6'), ('septic_mcf', '0.5'), ('septic_i', '1'),
  ('target_percent', '5')                 -- เป้าลดจากปีฐาน (%) ค่าเดิมของ TSATP4-CFO
on conflict (key) do nothing;

-- ผลต่อแถว: tCO2e = qty × kgco2e / 1000 · แยกก๊าซ (Scope 1) = qty × EF ก๊าซ × GWP / 1000
-- บ่อเกรอะ (calc = septic): qty = kg CH4 → tCO2e = qty × GWP CH4 ของรายการ / 1000 (เหมือน TSATP4-CFO saveSepticTx_)
create or replace view public.v_cfo_entry with (security_invoker = true) as
select e.id, e.month, e.status, a.department, a.name as activity, a.detail, s.scope, s.code as scope_code, s.name as scope_name,
  f.name as source, f.unit, e.qty, f.kgco2e,
  round(e.qty * case when a.calc = 'septic' then g.ch4 else f.kgco2e end / 1000, 6) as tco2e,
  round(e.qty * coalesce(f.co2, 0) * g.co2 / 1000, 6) as tco2e_co2,
  round(e.qty * (coalesce(f.ch4_fossil, 0) * g.ch4_fossil + case when a.calc = 'septic' then 1 else coalesce(f.ch4, 0) end * g.ch4) / 1000, 6) as tco2e_ch4,
  round(e.qty * coalesce(f.n2o, 0) * g.n2o / 1000, 6) as tco2e_n2o,
  round(e.qty * (coalesce(f.hfc, 0) * coalesce(f.hfc_gwp, 1) + coalesce(f.pfc, 0) * coalesce(f.pfc_gwp, 1)) / 1000, 6) as tco2e_fgas,
  e.activity_id,                                          -- เพิ่มท้ายสุด: create or replace view เพิ่มคอลัมน์ได้แค่ต่อท้าย
  round(e.qty * (coalesce(f.sf6, 0) * g.sf6 + coalesce(f.nf3, 0) * g.nf3) / 1000, 6) as tco2e_sf6_nf3,
  round(e.qty * coalesce(f.other, 0) * coalesce(f.other_gwp, 0) / 1000, 6) as tco2e_other,
  f.separate,                                             -- รายงานแยก: ไม่รวมในยอด Scope
  round(e.qty * coalesce(f.co2_bio, 0) / 1000, 6) as tco2e_bio  -- CO2 ชีวมวล รายงานแยก
from public.tx_cfo_entry e
join public.mt_cfo_activity a on a.id = e.activity_id
join public.mt_cfo_ef f on f.id = e.ef_id
join public.mt_cfo_scope s on s.code = f.scope_code
join public.mt_cfo_gwp g on g.code = e.gwp_code;

-- รวมรายเดือนต่อ Scope (Dashboard) · ไม่รวมรายการที่รายงานแยก
create or replace view public.v_cfo_month with (security_invoker = true) as
select month, scope, round(sum(tco2e), 6) as tco2e, count(*) as entries
from public.v_cfo_entry
where not separate
group by month, scope;

