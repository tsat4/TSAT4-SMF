-- ===== qcc: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_qcc_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_qcc_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_qcc_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_qcc_team add column if not exists department text;
alter table public.mt_qcc_team
  drop constraint if exists mt_qcc_team_role_check,
  add constraint mt_qcc_team_role_check check (role in ('admin', 'chairman', 'vice', 'auditor', 'owner', 'member')),
  drop constraint if exists mt_qcc_team_member_has_dept,
  add constraint mt_qcc_team_member_has_dept check ((role = 'member') = (department is not null)),
  drop constraint if exists mt_qcc_team_unique,
  add constraint mt_qcc_team_unique unique nulls not distinct (year, employee_id, role, team, area_id, department);
create index if not exists mt_qcc_team_lookup on public.mt_qcc_team (year, employee_id);
create unique index if not exists mt_qcc_team_one_owner on public.mt_qcc_team (year, area_id) where role = 'owner';

create table if not exists public.mt_qcc_setting (
  key text primary key,
  value text not null
);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_qcc · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_qcc', 'img_qcc', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;

-- ===== qcc: Project Planner =====

-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_qcc_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_qcc_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p12
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_qcc_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_qcc_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_qcc_task_year on public.mt_qcc_task (year, parent_id, sort_no);
-- วันที่ทำครบ 100% (server ใส่ให้) ใช้บอกเสร็จก่อนแผน / ตามแผน / ช้า เทียบกับ end_date · เพิ่มทีหลัง จึงใช้ add column (รันซ้ำได้)
alter table public.mt_qcc_task add column if not exists done_on date;

-- ===== qcc: โครงการกลุ่ม QCC (1 แถว = 1 กลุ่ม 1 เรื่อง) =====

-- ฟอร์ม FM-QMR-022…031 เก็บใน forms (jsonb) ตามรหัสฟอร์ม เช่น {"022": {...}, "023": {...}} · server ตรวจรูปแบบก่อนบันทึก
-- รูป (ผังก้างปลา / ก่อน / หลัง) อยู่ใน bucket img_qcc เก็บลิงก์ใน photos (jsonb)
-- cost_total (ฟอร์ม 030 ค่าแรง + อื่นๆ) และ return_month (ผลตอบแทนบาท/เดือน) server คำนวณจาก forms ทุกครั้งที่บันทึก
create table if not exists public.tx_qcc_project (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  reg_no text,                                            -- เลขทะเบียนกลุ่ม เช่น QCC-TSAT-P4-005
  group_name text not null,                               -- ชื่อกลุ่ม
  department text,                                        -- ฝ่าย
  topic text not null,                                    -- จดทะเบียนกิจกรรมเรื่อง
  leader_id text not null,                                -- หัวหน้ากลุ่ม (employee_id, Mx Data)
  manager_id text,                                        -- ผู้จัดการต้นสังกัด
  members text,                                           -- สมาชิกกลุ่ม
  start_month date,                                       -- ระยะเวลาดำเนินกิจกรรม (วันที่ 1 ของเดือน)
  end_month date,
  forms jsonb not null default '{}'::jsonb,
  photos jsonb not null default '{}'::jsonb,
  cost_total numeric not null default 0 check (cost_total >= 0),
  return_month numeric not null default 0 check (return_month >= 0),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED')),
  review_note text,
  reviewed_by text,
  reviewed_at timestamptz,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text,
  updated_at timestamptz,
  constraint tx_qcc_project_months check (end_month is null or start_month is null or end_month >= start_month)
);
create index if not exists tx_qcc_project_year on public.tx_qcc_project (year, status);

