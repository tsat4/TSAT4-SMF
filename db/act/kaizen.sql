-- ===== kaizen: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_kaizen_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_kaizen_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_kaizen_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_kaizen_team add column if not exists department text;
alter table public.mt_kaizen_team
  drop constraint if exists mt_kaizen_team_role_check,
  add constraint mt_kaizen_team_role_check check (role in ('admin', 'chairman', 'vice', 'auditor', 'owner', 'member')),
  drop constraint if exists mt_kaizen_team_member_has_dept,
  add constraint mt_kaizen_team_member_has_dept check ((role = 'member') = (department is not null)),
  drop constraint if exists mt_kaizen_team_unique,
  add constraint mt_kaizen_team_unique unique nulls not distinct (year, employee_id, role, team, area_id, department);
create index if not exists mt_kaizen_team_lookup on public.mt_kaizen_team (year, employee_id);
create unique index if not exists mt_kaizen_team_one_owner on public.mt_kaizen_team (year, area_id) where role = 'owner';

create table if not exists public.mt_kaizen_setting (
  key text primary key,
  value text not null
);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_kaizen · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_kaizen', 'img_kaizen', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;

-- ===== kaizen: Project Planner =====

-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_kaizen_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_kaizen_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p5
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_kaizen_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_kaizen_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_kaizen_task_year on public.mt_kaizen_task (year, parent_id, sort_no);

-- ===== kaizen: ทีมตัวแทนแผนก (เป้าส่งต่อปี + ผู้จัดการประเมิน) & ใบ Kaizen (FM-QSM-039) =====

-- ตัวแทนแผนก (role = member): เป้าจำนวนเรื่องที่ต้องส่งต่อปี (target_count) และผู้จัดการประเมิน Kaizen ของแผนก (manager_id = employee_id)
alter table public.mt_kaizen_team
  add column if not exists target_count integer not null default 0 check (target_count >= 0),
  add column if not exists manager_id text;

-- 1 แถว = 1 ใบ · ผู้เสนอ = employee_id (Mx Data, คนเดิมส่งซ้ำได้หลายเรื่อง) · รูปก่อน/หลัง 16:9 ใน bucket img_kaizen
-- เงินลงทุน = ค่าแรง + ค่าอุปกรณ์ · ระยะเวลาคืนทุน (เดือน) = เงินลงทุน ÷ ผลตอบแทนต่อเดือน (server คำนวณ ไม่เก็บ)
create table if not exists public.tx_kaizen_entry (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  reg_no text unique,                                     -- ลงทะเบียนเลขที่ KZ-2026-0001 (server ออกให้)
  title text not null,                                    -- เรื่อง
  kind text not null default 'person' check (kind in ('person', 'team', 'qcc')),  -- บุคคล / ทีม / มาจาก QCC
  employee_id text not null,
  department text,
  members text,                                           -- สมาชิกทีม
  submitted_on date not null default current_date,
  before_text text,                                       -- สภาพปัจจุบัน หรือ ปัญหา ก่อนปรับปรุง
  after_text text,                                        -- วิธีการปรับปรุง
  before_photo text,
  after_photo text,
  types text[] not null default '{}' check (types <@ array['Q', 'C', 'D', 'S', 'M', 'E', 'O']::text[]),  -- Q C D S M E อื่นๆ
  other_type text,
  cost_labor numeric not null default 0 check (cost_labor >= 0),        -- ค่าแรง (บาท)
  cost_material numeric not null default 0 check (cost_material >= 0),  -- ค่าอุปกรณ์ (บาท)
  return_month numeric not null default 0 check (return_month >= 0),    -- ผลตอบแทน (บาท/เดือน)
  benefit text,                                           -- ผลที่คิดเป็นเงินไม่ได้
  status text not null default 'DRAFT' check (status in ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED')),
  review_note text,
  reviewed_by text,
  reviewed_at timestamptz,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text,
  updated_at timestamptz
);
-- ด้านหลังฟอร์ม (การประเมินของหัวหน้างาน / ผู้จัดการ): ก1 ชั่วโมงที่ลด (เกรด A–I) · ก2 บาทที่ลดได้ (เกรด Q–Z) · ข 6 หัวข้อ 0–5 คะแนน (เกรด J–P)
alter table public.tx_kaizen_entry
  add column if not exists start_on date,                 -- เริ่มปฏิบัติวันที่
  add column if not exists end_on date,                   -- สิ้นสุด ณ วันที่
  add column if not exists saved_hours numeric check (saved_hours >= 0),  -- ก1 จำนวนชั่วโมงทำงานที่ลดลง (ชม./ปี)
  add column if not exists saved_baht numeric check (saved_baht >= 0),    -- ก2 จำนวนเงินที่ลดได้ (บาท)
  add column if not exists scores smallint[] check (scores is null or (cardinality(scores) = 6 and scores <@ array[0, 1, 2, 3, 4, 5]::smallint[])),
  add column if not exists eval_grade text,               -- เกรดที่คำนวณได้ (เช่น A / Q / J)
  add column if not exists eval_reward numeric check (eval_reward >= 0);  -- รางวัลรวม (บาท)
create index if not exists tx_kaizen_entry_year on public.tx_kaizen_entry (year, status);

