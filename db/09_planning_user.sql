create table if not exists public.mt_planning_user (
  id bigint generated by default as identity primary key,
  employee_id text not null references public.mt_main_employee (employee_id) on delete cascade,
  role text not null check (role in ('viewer', 'user', 'admin')),
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (employee_id)
);

alter table public.mt_planning_user enable row level security;

