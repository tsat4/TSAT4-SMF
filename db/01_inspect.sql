-- อ่านอย่างเดียว ไม่แก้ข้อมูล ใช้รันใน Supabase SQL Editor ของทั้ง 2 โปรเจกต์ (TX และ MX)
-- ผลที่ได้คือ 1 ช่อง (ddl) ให้ copy ทั้งช่องส่งกลับให้ AI เพื่อเขียน SQL ย้ายตาราง
with
rel as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'v')
),
enums as (
  select 10 as ord, t.typname as name,
    format('create type public.%I as enum (%s);', t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)) as ddl
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname
),
tables as (
  select 20, r.relname,
    format(E'create table public.%I (\n%s\n);  -- rows: %s', r.relname,
      string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else
          case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
               when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end end,
        case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum),
      (xpath('/row/c/text()', query_to_xml(format('select count(*) as c from public.%I', r.relname), false, true, '')))[1]::text)
  from rel r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where r.relkind = 'r' group by r.relname
),
cons as (
  select case c.contype when 'f' then 40 else 30 end, r.relname,
    format('alter table public.%I add constraint %I %s;', r.relname, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join rel r on r.oid = c.conrelid
),
idx as (
  select 50, r.relname, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join rel r on r.oid = i.indrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
),
rls as (
  select 60, r.relname, format('alter table public.%I enable row level security;', r.relname)
  from rel r where r.relrowsecurity
  union all
  select 61, p.tablename, format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename, p.permissive, p.cmd,
    array_to_string(p.roles, ', '), coalesce(' using (' || p.qual || ')', ''), coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p where p.schemaname = 'public'
),
fns as (
  select 70, p.proname, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
trg as (
  select 80, r.relname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join rel r on r.oid = t.tgrelid where not t.tgisinternal
),
views as (
  select 90, r.relname, format(E'create view public.%I as\n%s', r.relname, pg_get_viewdef(r.oid))
  from rel r where r.relkind = 'v'
),
allddl(ord, name, ddl) as (
  select * from enums union all select * from tables union all select * from cons union all select * from idx
  union all select * from rls union all select * from fns union all select * from trg union all select * from views
)
select '-- inspected ' || now()::date || E'\n\n' || string_agg(ddl, E'\n\n' order by ord, name, ddl) as ddl
from allddl;
