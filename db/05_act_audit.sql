-- spec: docs/specs/act-5s.md · ทดสอบ: npm run test:act
-- ทุกตารางแยกข้อมูลด้วย activity (id ตามเมนู เช่น '5s', 'safety')

-- ===== Setting =====

create table if not exists public.mt_act_area (
  id bigint generated by default as identity primary key,
  activity text not null,
  code text not null,                                   -- เช่น A01
  area_type text not null check (area_type in ('โรงงาน', 'สำนักงาน')),
  name text not null,
  section text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (activity, code)
);

-- เจ้าของพื้นที่: ปีละ 1 คนต่อพื้นที่ 1 คนดูแลได้หลายพื้นที่
create table if not exists public.mt_act_area_owner (
  year integer not null check (year between 2000 and 2100),
  area_id bigint not null references public.mt_act_area (id) on delete cascade,
  employee_id text not null,
  primary key (year, area_id)
);
create index if not exists mt_act_area_owner_employee on public.mt_act_area_owner (year, employee_id);

-- ทีมรายปี: admin = ดูแล Setting, chairman = หัวหน้าทีมตรวจ, auditor = ผู้ตรวจในทีม A–Z
create table if not exists public.mt_act_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  activity text not null,
  employee_id text not null,
  role text not null check (role in ('admin', 'chairman', 'auditor')),
  team text check (team ~ '^[A-Z]$'),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_act_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_act_team_unique unique nulls not distinct (year, activity, employee_id, role, team)
);
create index if not exists mt_act_team_lookup on public.mt_act_team (year, activity, employee_id);

-- หัวข้อตรวจรายปี (5S: 25 ข้อ, s_group 1–5)
create table if not exists public.mt_act_checklist (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  activity text not null,
  item_no integer not null check (item_no between 1 and 200),
  s_group integer not null check (s_group between 1 and 20),
  title text not null,
  score_max integer not null default 5 check (score_max > 0),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (year, activity, item_no)
);

-- แผนตรวจ Committee: พื้นที่ × เดือน × สัปดาห์ (W1 = 1–7, W2 = 8–14, W3 = 15–21, W4 = 22–สิ้นเดือน)
create table if not exists public.mt_act_audit_plan (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  activity text not null,
  area_id bigint not null references public.mt_act_area (id) on delete cascade,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 4),
  round integer check (round between 1 and 6),
  team text check (team ~ '^[A-Z]$'),
  created_at timestamptz not null default now(),
  unique (year, activity, area_id, month, week)
);

-- ค่าตั้งต้นของแต่ละกิจกรรม
create table if not exists public.mt_act_setting (
  activity text not null,
  key text not null,
  value text not null,
  primary key (activity, key)
);
insert into public.mt_act_setting (activity, key, value) values
  ('5s', 'pass_percent', '80'),                -- ผ่านเมื่อ % ≥ 80
  ('5s', 'issue_score', '3'),                  -- Committee: ข้อที่ได้ ≤ 3 ต้องเปิด Issue
  ('5s', 'issue_due_days_before_next', '10'),  -- แก้ให้เสร็จก่อนตรวจรอบถัดไป 10 วัน
  ('5s', 'issue_photo_max', '1'),              -- รูปปัญหา 16:9 1 รูป
  ('5s', 'self_audit_due_day', '10')           -- Self Audit ภายในวันที่ 10 ของเดือน
on conflict (activity, key) do nothing;

-- ===== transaction =====

create table if not exists public.tx_act_audit (
  id bigint generated by default as identity primary key,
  audit_no text not null unique,                        -- C|S-<area>-<ddMMyy>-<seq> เช่น C-A01-040926-01
  activity text not null,
  year integer not null check (year between 2000 and 2100),
  audit_type text not null check (audit_type in ('SELF', 'COMMITTEE')),
  area_id bigint not null references public.mt_act_area (id),
  plan_id bigint references public.mt_act_audit_plan (id) on delete set null,
  team text,
  audited_at timestamptz not null,
  total_score numeric(8, 2) not null default 0,
  percent_score numeric(5, 2) not null default 0,
  result text check (result in ('PASS', 'NEED_IMPROVE')),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'COMPLETED')),
  created_by text,
  created_at timestamptz not null default now()
);
create index if not exists tx_act_audit_lookup on public.tx_act_audit (activity, year, area_id, audited_at);

create table if not exists public.tx_act_audit_score (
  audit_id bigint not null references public.tx_act_audit (id) on delete cascade,
  checklist_id bigint not null references public.mt_act_checklist (id),
  score numeric(5, 2) not null check (score >= 0),     -- 0 = Issue เดิมไม่มี Action
  primary key (audit_id, checklist_id)
);

-- คนในใบตรวจ: assigned = ได้รับมอบหมาย, participated = ไปตรวจจริง, receiver = ผู้รับตรวจในพื้นที่
create table if not exists public.tx_act_audit_person (
  audit_id bigint not null references public.tx_act_audit (id) on delete cascade,
  employee_id text not null,
  kind text not null check (kind in ('assigned', 'participated', 'receiver')),
  primary key (audit_id, employee_id, kind)
);

create table if not exists public.tx_act_issue (
  id bigint generated by default as identity primary key,
  issue_no text not null unique,                        -- ISS0001
  audit_id bigint not null references public.tx_act_audit (id) on delete cascade,
  area_id bigint not null references public.mt_act_area (id),
  checklist_id bigint not null references public.mt_act_checklist (id),
  score numeric(5, 2) not null,
  description text not null,
  issue_date date not null,
  responsible_id text,
  due_date date,                                        -- null = รอกำหนดรอบถัดไป
  action_description text,
  action_date date,
  status text not null default 'OPEN' check (status in ('OPEN', 'ON_PLAN', 'WAIT_VERIFY', 'OVERDUE', 'CLOSED')),
  verify_audit_no text,                                 -- ใบตรวจรอบถัดไปที่ยืนยันผล (เก็บเป็นเลขเพราะข้อมูลเดิมบางใบไม่มีในระบบ)
  final_score numeric(5, 2),
  closed_by text,
  closed_at date
);
create index if not exists tx_act_issue_area on public.tx_act_issue (area_id, status);

create table if not exists public.tx_act_issue_photo (
  id bigint generated by default as identity primary key,
  issue_id bigint not null references public.tx_act_issue (id) on delete cascade,
  kind text not null check (kind in ('BEFORE', 'AFTER')),
  url text not null,
  created_at timestamptz not null default now(),
  unique (issue_id, url)
);

-- ===== Dashboard =====

-- % ของแต่ละ ส ต่อใบตรวจ (Summary / Ranking) · security_invoker = ใช้สิทธิ์ของคนเรียก ไม่ข้าม RLS
create or replace view public.v_act_audit_group with (security_invoker = true) as
select s.audit_id, c.s_group,
  sum(s.score) as score,
  sum(c.score_max) as score_max,
  round(sum(s.score) * 100.0 / nullif(sum(c.score_max), 0), 2) as percent
from public.tx_act_audit_score s
join public.mt_act_checklist c on c.id = s.checklist_id
group by s.audit_id, c.s_group;

