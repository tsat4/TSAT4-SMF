-- ขั้นที่ 2: รันใน MX ก่อนคัดลอกข้อมูล
-- สร้างตาราง tx_* เปล่าให้โครงตรงกับ TX
-- identity เป็น by default เพื่อคัดลอก id เดิมได้
-- ยังไม่ใส่ trigger เพื่อไม่ให้ทำงานซ้ำตอนคัดลอก

create table public.tx_sto_requisition (
  id bigint generated by default as identity not null,
  requested_by text not null,
  costcenter text not null,
  status text default 'cart'::text not null,
  submitted_at timestamp with time zone,
  accepted_by text,
  accepted_at timestamp with time zone,
  preparing_at timestamp with time zone,
  ready_at timestamp with time zone,
  received_by text,
  received_at timestamp with time zone,
  cancelled_at timestamp with time zone,
  prepare_lead interval,
  receive_lead interval,
  note text,
  created_at timestamp with time zone default now() not null,
  updated_at timestamp with time zone default now() not null
);

create table public.tx_sto_requisition_line (
  id bigint generated by default as identity not null,
  requisition_id bigint not null,
  costcenter text not null,
  material text not null,
  qty numeric(14,3) not null,
  created_at timestamp with time zone default now() not null,
  updated_at timestamp with time zone default now() not null
);

create table public.tx_sto_issue (
  id bigint generated by default as identity not null,
  requisition_id bigint not null,
  requisition_line_id bigint not null,
  costcenter text not null,
  material text not null,
  qty numeric(14,3) not null,
  issued_at timestamp with time zone default now() not null
);

alter table public.tx_sto_requisition add constraint tx_sto_requisition_pkey primary key (id);
alter table public.tx_sto_requisition add constraint tx_sto_requisition_id_costcenter_key unique (id, costcenter);
alter table public.tx_sto_requisition add constraint tx_sto_requisition_status_check check (status = any (array['cart'::text, 'submitted'::text, 'accepted'::text, 'preparing'::text, 'ready'::text, 'received'::text, 'cancelled'::text]));
alter table public.tx_sto_requisition add constraint tx_sto_requisition_check check (
  ((status = 'cart'::text) and (submitted_at is null) and (accepted_at is null) and (preparing_at is null) and (ready_at is null) and (received_at is null) and (cancelled_at is null))
  or ((status = 'submitted'::text) and (submitted_at is not null) and (accepted_at is null) and (preparing_at is null) and (ready_at is null) and (received_at is null) and (cancelled_at is null))
  or ((status = 'accepted'::text) and (submitted_at is not null) and (accepted_at is not null) and (accepted_by is not null) and (preparing_at is null) and (ready_at is null) and (received_at is null) and (cancelled_at is null))
  or ((status = 'preparing'::text) and (submitted_at is not null) and (accepted_at is not null) and (preparing_at is not null) and (ready_at is null) and (received_at is null) and (cancelled_at is null))
  or ((status = 'ready'::text) and (submitted_at is not null) and (accepted_at is not null) and (preparing_at is not null) and (ready_at is not null) and (received_at is null) and (cancelled_at is null))
  or ((status = 'received'::text) and (submitted_at is not null) and (accepted_at is not null) and (preparing_at is not null) and (ready_at is not null) and (received_at is not null) and (received_by is not null) and (cancelled_at is null))
  or ((status = 'cancelled'::text) and (cancelled_at is not null) and (received_at is null))
);

