-- ขั้นที่ 4: รันส่วนนี้หลังคัดลอกข้อมูลแล้ว (พร้อมกับ db/03_receive_rpc.sql)
-- set_updated_at มีอยู่ใน MX แล้ว ไม่สร้างซ้ำ

create or replace function public.tx_sto_apply_costcenter(p_id bigint, p_employee text, p_costcenter text)
returns void
language plpgsql
set search_path to ''
as $function$
begin
  set constraints public.tx_sto_requisition_line_requisition_id_costcenter_fkey deferred;
  update public.tx_sto_requisition
  set costcenter = p_costcenter
  where id = p_id
    and requested_by = p_employee
    and status = 'cart';
  if not found then
    raise exception 'cart not found';
  end if;
  update public.tx_sto_requisition_line
  set qty = qty
  where requisition_id = p_id;
end;
$function$;

create or replace function public.tx_sto_issue_apply()
returns trigger
language plpgsql
set search_path to ''
as $function$
begin
  if current_setting('smf.issuing', true) is distinct from '1' then
    raise exception 'stock issue is created when the requester confirms';
  end if;
  if not exists (
    select 1
    from public.tx_sto_requisition_line as line
    where line.id = new.requisition_line_id
      and line.requisition_id = new.requisition_id
      and line.costcenter = new.costcenter
      and line.material = new.material
      and line.qty = new.qty
  ) then
    raise exception 'issue does not match the requisition line';
  end if;
  return new;
end;
$function$;

create or replace function public.tx_sto_issue_freeze()
returns trigger
language plpgsql
set search_path to ''
as $function$
begin
  raise exception 'a stock issue cannot be changed';
end;
$function$;

create or replace function public.tx_sto_requisition_guard()
returns trigger
language plpgsql
set search_path to ''
as $function$
begin
  if tg_op = 'INSERT' then
    if new.status <> 'cart' then
      raise exception 'new requisition starts as cart';
    end if;
  else
    if new.requested_by is distinct from old.requested_by then
      raise exception 'requester cannot change';
    end if;
    if new.costcenter is distinct from old.costcenter then
      if old.status <> 'cart' then
        raise exception 'costcenter changes only while the requisition is a cart';
      end if;
    end if;
  end if;

  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    if old.status in ('received', 'cancelled') then
      raise exception 'requisition is closed';
    end if;

    if new.status = 'cancelled' and old.status in ('cart', 'submitted', 'accepted', 'preparing', 'ready') then
      new.cancelled_at = coalesce(new.cancelled_at, now());
    elsif old.status = 'cart' and new.status = 'submitted' then
      if not exists (
        select 1 from public.tx_sto_requisition_line as line
        where line.requisition_id = new.id
      ) then
        raise exception 'cart is empty';
      end if;
      new.submitted_at = coalesce(new.submitted_at, now());
    elsif old.status = 'submitted' and new.status = 'accepted' then
      if new.accepted_by is null then
        raise exception 'accepted_by is required';
      end if;
      new.accepted_at = coalesce(new.accepted_at, now());
    elsif old.status = 'accepted' and new.status = 'preparing' then
      new.preparing_at = coalesce(new.preparing_at, now());
    elsif old.status = 'preparing' and new.status = 'ready' then
      new.ready_at = coalesce(new.ready_at, now());
    elsif old.status = 'ready' and new.status = 'received' then
      if new.received_by is distinct from new.requested_by then
        raise exception 'requester confirms receipt';
      end if;
      new.received_at = coalesce(new.received_at, now());
    else
      raise exception 'status change is not allowed';
    end if;
  end if;

  new.prepare_lead = new.ready_at - new.accepted_at;
  new.receive_lead = new.received_at - new.submitted_at;
  return new;
end;
$function$;

create or replace function public.tx_sto_requisition_issue()
returns trigger
language plpgsql
set search_path to ''
as $function$
begin
  if new.status = 'received' and old.status is distinct from 'received' then
    perform set_config('smf.issuing', '1', true);
    insert into public.tx_sto_issue (requisition_id, requisition_line_id, costcenter, material, qty)
    select line.requisition_id, line.id, line.costcenter, line.material, line.qty
    from public.tx_sto_requisition_line as line
    where line.requisition_id = new.id;
  end if;
  return new;
end;
$function$;

create or replace function public.tx_sto_requisition_line_bind()
returns trigger
language plpgsql
set search_path to ''
as $function$
declare
  v_status text;
  v_costcenter text;
begin
  if tg_op = 'UPDATE' and new.requisition_id is distinct from old.requisition_id then
    raise exception 'line cannot move to another requisition';
  end if;

  select requisition.status, requisition.costcenter
  into v_status, v_costcenter
  from public.tx_sto_requisition as requisition
  where requisition.id = new.requisition_id;

  if v_status is null then
    raise exception 'requisition not found';
  end if;
  if v_status <> 'cart' then
    raise exception 'lines change only while the requisition is a cart';
  end if;

  new.costcenter = v_costcenter;
  return new;
end;
$function$;

create or replace function public.tx_sto_requisition_line_lock()
returns trigger
language plpgsql
set search_path to ''
as $function$
declare
  v_status text;
begin
  select requisition.status
  into v_status
  from public.tx_sto_requisition as requisition
  where requisition.id = old.requisition_id;

  if v_status is distinct from 'cart' then
    raise exception 'lines change only while the requisition is a cart';
  end if;
  return old;
end;
$function$;

