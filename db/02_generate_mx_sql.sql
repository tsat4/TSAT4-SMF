-- ขั้นที่ 2: รันใน SQL Editor ของโปรเจกต์ TX (อ่านอย่างเดียว ไม่แก้อะไรใน TX)
-- ผลที่ได้มี 2 แถว แต่ละแถวเป็น SQL ที่พร้อมรันใน MX:
--   A_before_copy  enum, sequence, ตาราง tx_*, constraint, index, RLS, policy, function  → รันใน MX ก่อนคัดลอกข้อมูล
--   B_after_copy   trigger และ view                                                  → รันใน MX หลังคัดลอกข้อมูลเสร็จ
-- ให้ save เป็นไฟล์ db/02a_mx_before_copy.sql และ db/02b_mx_after_copy.sql
-- SQL ที่ได้รันซ้ำได้: ของที่มีอยู่แล้วจะข้ามไป แต่ถ้า MX มี function หรือ enum ชื่อซ้ำที่เนื้อหาต่างกัน จะหยุดพร้อม error ไม่เขียนทับ
-- identity แบบ "generated always" จะเปลี่ยนเป็น "by default" เพื่อให้คัดลอก id เดิมได้
with
rel as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'v') and c.relname like 'tx\_%'
),
enum_types as (
  select distinct t.oid, t.typname
  from rel r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  join pg_type t on t.oid = a.atttypid and t.typtype = 'e'
),
enums as (
  select 10 as ord, t.typname::text as name, format($f$do $smf$ begin
  if to_regtype(%1$L) is null then
    create type %2$s as enum (%3$s);
  elsif (select array_agg(enumlabel::text order by enumsortorder) from pg_enum where enumtypid = to_regtype(%1$L)) is distinct from %4$L::text[] then
    raise exception 'MX already has a different type %%', %1$L;
  end if;
end $smf$;$f$,
    'public.' || quote_ident(t.typname), 'public.' || quote_ident(t.typname),
    string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder),
    array_agg(e.enumlabel::text order by e.enumsortorder)) as sql
  from enum_types t join pg_enum e on e.enumtypid = t.oid group by t.typname
),
seqs as (
  select 20, s.relname::text, format('create sequence if not exists public.%I;', s.relname)
  from pg_depend d join pg_class s on s.oid = d.objid and s.relkind = 'S' join rel r on r.oid = d.refobjid
  where d.deptype = 'a'
),
tables as (
  select 30, r.relname::text,
    format(E'create table if not exists public.%I (\n%s\n);', r.relname,
      string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attidentity in ('a', 'd') then ' generated by default as identity'
             when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
             when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum))
  from rel r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where r.relkind = 'r' group by r.relname
),
seq_owner as (
  select 35, s.relname::text, format('alter sequence public.%I owned by public.%I.%I;', s.relname, r.relname, a.attname)
  from pg_depend d join pg_class s on s.oid = d.objid and s.relkind = 'S' join rel r on r.oid = d.refobjid
  join pg_attribute a on a.attrelid = r.oid and a.attnum = d.refobjsubid
  where d.deptype = 'a'
),
cons as (
  select case c.contype when 'f' then 50 else 40 end, r.relname::text || c.conname,
    format($f$do $smf$ begin alter table public.%I add constraint %I %s; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $smf$;$f$,
      r.relname, c.conname, pg_get_constraintdef(c.oid))
  from pg_constraint c join rel r on r.oid = c.conrelid
  where c.contype in ('p', 'u', 'c', 'x', 'f')
),
idx as (
  select 60, r.relname::text, regexp_replace(pg_get_indexdef(i.indexrelid), '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';'
  from pg_index i join rel r on r.oid = i.indrelid
  where not exists (select 1 from pg_constraint c where c.conindid = i.indexrelid)
),
rls as (
  select 70, r.relname::text, format('alter table public.%I enable row level security;', r.relname)
  from rel r where r.relrowsecurity
  union all
  select 71, p.tablename::text || p.policyname,
    format($f$do $smf$ begin create policy %I on public.%I as %s for %s to %s%s%s; exception when duplicate_object then null; end $smf$;$f$,
      p.policyname, p.tablename, p.permissive, p.cmd, array_to_string(p.roles, ', '),
      coalesce(' using (' || p.qual || ')', ''), coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p where p.schemaname = 'public' and p.tablename like 'tx\_%'
),
fns as (
  select 80, p.proname::text, format($f$do $smf$ declare f oid; begin
  select p.oid into f from pg_proc p where p.pronamespace = 'public'::regnamespace and p.proname = %1$L and pg_get_function_identity_arguments(p.oid) = %2$L;
  if f is null then
    execute %3$L;
  elsif pg_get_functiondef(f) <> %3$L then
    raise exception 'MX already has a different function public.%%(%%)', %1$L, %2$L;
  end if;
end $smf$;$f$, p.proname, pg_get_function_identity_arguments(p.oid), pg_get_functiondef(p.oid))
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
trg as (
  select 90, r.relname::text || t.tgname,
    case when t.tgconstraint <> 0
      then format($f$do $smf$ begin %s; exception when duplicate_object then null; end $smf$;$f$, pg_get_triggerdef(t.oid))
      else regexp_replace(pg_get_triggerdef(t.oid), '^CREATE TRIGGER ', 'CREATE OR REPLACE TRIGGER ') || ';' end
  from pg_trigger t join rel r on r.oid = t.tgrelid where not t.tgisinternal
),
views as (
  select 95, r.relname::text, format(E'create or replace view public.%I as\n%s', r.relname, pg_get_viewdef(r.oid))
  from rel r where r.relkind = 'v'
),
a_part(ord, name, sql) as (
  select * from enums union all select * from seqs union all select * from tables union all select * from seq_owner
  union all select * from cons union all select * from idx union all select * from rls union all select * from fns
),
b_part(ord, name, sql) as (
  select * from trg union all select * from views
)
select 'A_before_copy' as step,
  E'-- รันใน MX ก่อนคัดลอกข้อมูล (สร้างจาก TX ' || now()::date || E')\n\n' || coalesce(string_agg(sql, E'\n\n' order by ord, name), '-- (ไม่มี)') as sql
from a_part
union all
select 'B_after_copy',
  E'-- รันใน MX หลัง npm run migrate:tx เสร็จ (สร้างจาก TX ' || now()::date || E')\n\n' || coalesce(string_agg(sql, E'\n\n' order by ord, name), '-- (ไม่มี)')
from b_part;
