// SQL for one activity in Tx Data, from one template so every activity has the same shape.
// Every activity gets team + settings + Project Planner + photo bucket; checklist-audit activities add the audit tables.
//   node scripts/act-sql.js 5s                -> db/act/5s.sql       (with checklist audit tables)
//   node scripts/act-sql.js 100p --no-audit   -> db/act/100p.sql     (no audit tables)
//   node scripts/act-sql.js cfo --no-audit    -> db/act/cfo.sql      (+ CFO tables: scope, gwp, ef, activity, entry)
//   node scripts/act-sql.js 5s --add-task     -> db/act/5s_task.sql  (add the Planner to a running database, copy the old Gantt plan)
// Table names: mt_<key>_* (setting) / tx_<key>_* (transaction), key = activity id without symbols (e-day -> eday).
// Keep server/modules/act/common.js tablesOf() in step with the names here.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ACTIVITIES = ['100p', '5s', 'cfo', 'e-day', 'kaizen', 'lean', 'qcc', 'safety', 'smf'];

// Project Planner table (main items + sub items), see docs/specs/act-planner.md.
function taskTableSql(activity, k) {
  return `
-- ===== ${activity}: Project Planner =====

-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_${k}_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_${k}_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p5
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_${k}_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_${k}_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_${k}_task_year on public.mt_${k}_task (year, parent_id, sort_no);
`;
}

// Add the Planner to an activity that already runs, and copy its old Gantt plan (mt_<key>_plan) once:
// one main item per (year, title); a title with one date range keeps its dates, several ranges become sub items.
//   node scripts/act-sql.js 5s --add-task -> db/act/5s_task.sql
export function actTaskSql(activity) {
  if (!ACTIVITIES.includes(activity)) throw new Error(`unknown activity ${activity}`);
  const k = activity.replace(/[^a-z0-9]/g, '');
  return `-- กิจกรรม ${activity}: เพิ่ม Project Planner ให้ฐานที่ใช้งานอยู่ — รันใน **Tx Data** (รันซ้ำได้) · สร้างจาก scripts/act-sql.js ห้ามแก้มือ
-- คัดลอกแผน Gantt เดิม (mt_${k}_plan ถ้ามี) เข้า Planner ครั้งเดียว ตอนที่ mt_${k}_task ยังว่าง (ไม่ลบแผนเดิม)
${taskTableSql(activity, k)}
do $$ begin
  if to_regclass('public.mt_${k}_plan') is not null and not exists (select 1 from public.mt_${k}_task) then
    with g as (
      select extract(year from start_date)::int as year, title, count(*) as n, min(start_date) as first_start,
        min(start_date) as start_date, max(end_date) as end_date,
        bool_and(status = 'done') as done, min(created_by) as created_by, max(responsible) as responsible, max(detail) as detail
      from public.mt_${k}_plan where status <> 'cancelled'
      group by 1, 2
    )
    insert into public.mt_${k}_task (year, sort_no, title, start_date, end_date, progress, note, created_by)
    select year, row_number() over (partition by year order by first_start, title), title,
      case when n = 1 then start_date end, case when n = 1 then end_date end,
      case when n = 1 and done then 100 else 0 end,
      case when n = 1 then nullif(concat_ws(' · ', detail, 'ผู้รับผิดชอบ: ' || responsible), '') end,
      coalesce(created_by, 'import')
    from g;

    insert into public.mt_${k}_task (year, parent_id, sort_no, title, start_date, end_date, progress, note, created_by)
    select t.year, t.id, row_number() over (partition by t.id order by p.start_date, p.id), p.title, p.start_date, p.end_date,
      case when p.status = 'done' then 100 else 0 end,
      nullif(concat_ws(' · ', p.detail, 'ผู้รับผิดชอบ: ' || p.responsible), ''), p.created_by
    from public.mt_${k}_plan p
    join public.mt_${k}_task t on t.parent_id is null and t.title = p.title and t.year = extract(year from p.start_date)::int and t.start_date is null
    where p.status <> 'cancelled';
  end if;
end $$;

${'alter table public.mt_' + k + '_task enable row level security;'}

-- ตรวจ: main / sub = ข้อหลัก / ข้อรองใน Planner (เทียบกับแผนเดิมใน mt_${k}_plan ที่ไม่ได้ยกเลิก)
select (select count(*) from public.mt_${k}_task where parent_id is null) as main,
  (select count(*) from public.mt_${k}_task where parent_id is not null) as sub;

notify pgrst, 'reload schema';
`;
}

// Carbon Footprint for Organization (CFO): 15 Excel sheets -> 5 tables + 2 views. docs/specs/act-cfo.md
// Totals are not stored: v_cfo_entry computes them from qty × the EF and GWP the entry points at.
function cfoSql(k) {
  return `
-- ===== cfo: Carbon Footprint for Organization =====

-- หมวดการปล่อย 23 หมวด (Scope 1: 1-1…1-4, Scope 2: 2-1…2-4, Scope 3: 3-1…3-15)
create table if not exists public.mt_${k}_scope (
  code text primary key check (code ~ '^[1-3]-[0-9]{1,2}$'),
  scope smallint not null check (scope between 1 and 3),
  name text not null,
  name_th text
);

-- ค่า GWP ต่อก๊าซ (เช่น AR5) ใช้คูณ kg ก๊าซ -> kgCO2e
create table if not exists public.mt_${k}_gwp (
  code text primary key,                                  -- AR5
  co2 numeric not null default 1,
  ch4_fossil numeric not null default 0,
  ch4 numeric not null default 0,
  n2o numeric not null default 0,
  sf6 numeric not null default 0,
  nf3 numeric not null default 0,
  reference text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- Emission factor ทุก Scope ในตารางเดียว · kgco2e = ต่อ 1 หน่วย (รวมทุกก๊าซ) · ค่าแยกก๊าซมีเฉพาะ Scope 1
-- ค่าที่ถูกใช้แล้วห้ามแก้ ถ้าค่าเปลี่ยนให้เพิ่มแถวใหม่แล้วปิดแถวเดิม (Inactive) ผลย้อนหลังจะไม่เปลี่ยน
create table if not exists public.mt_${k}_ef (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (sc1021026-091)
  scope_code text not null references public.mt_${k}_scope (code),
  kind text,                                              -- On-Road / Off-Road หรือกลุ่มของ Scope 3
  name text not null,
  detail text,
  unit text not null,
  kgco2e numeric check (kgco2e >= 0),                     -- ว่าง = ยังไม่มีค่า ใช้บันทึกไม่ได้
  co2 numeric, ch4_fossil numeric, ch4 numeric, n2o numeric, hfc numeric, pfc numeric,
  reference text,
  year integer,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);
create index if not exists mt_${k}_ef_scope on public.mt_${k}_ef (scope_code, status);

-- กิจกรรมที่ต้องเก็บข้อมูลทุกเดือน (รถผู้บริหาร, Forklift, ไฟฟ้า ...) ของหน่วยงานไหน ใช้ EF ตัวไหน
create table if not exists public.mt_${k}_activity (
  id bigint generated by default as identity primary key,
  code text unique,                                       -- รหัสเดิมจาก Excel (ac1051026-001)
  ef_id bigint not null references public.mt_${k}_ef (id),
  gwp_code text not null references public.mt_${k}_gwp (code),
  department text not null,
  name text not null,
  detail text,
  calc text check (calc in ('septic')),                   -- ปริมาณคำนวณจากสูตร (septic = บ่อเกรอะ ค่าตั้งต้นใน mt_${k}_setting)
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- ข้อมูลรายเดือน 1 แถว = 1 กิจกรรม × 1 เดือน · ef_id / gwp_code = ค่าที่ใช้ตอนบันทึก (คัดลอกจากกิจกรรม)
create table if not exists public.tx_${k}_entry (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.mt_${k}_activity (id),
  month date not null check (extract(day from month) = 1),
  qty numeric not null check (qty >= 0),
  ef_id bigint not null references public.mt_${k}_ef (id),
  gwp_code text not null references public.mt_${k}_gwp (code),
  inputs jsonb,                                           -- ค่าที่กรอกให้สูตร calc เช่น {"people": 250, "days": 26}
  doc text,                                               -- ลิงก์เอกสาร/รูปหลักฐาน (bucket img_${k})
  status text not null default 'DRAFT' check (status in ('DRAFT', 'CONFIRMED')),
  remark text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_by text,
  updated_at timestamptz,
  unique (activity_id, month)
);
create index if not exists tx_${k}_entry_month on public.tx_${k}_entry (month);

-- ค่าตั้งต้นบ่อเกรอะ (IPCC): kg CH4 = คน × วัน × BOD × 0.001 × B0 × MCF × I
insert into public.mt_${k}_setting (key, value) values
  ('septic_bod', '40'), ('septic_b0', '0.6'), ('septic_mcf', '0.5'), ('septic_i', '1')
on conflict (key) do nothing;

-- ผลต่อแถว: tCO2e = qty × kgco2e / 1000 · แยกก๊าซ (Scope 1) = qty × EF ก๊าซ × GWP / 1000
create or replace view public.v_${k}_entry with (security_invoker = true) as
select e.id, e.month, e.status, a.department, a.name as activity, a.detail, s.scope, s.code as scope_code, s.name as scope_name,
  f.name as source, f.unit, e.qty, f.kgco2e,
  round(e.qty * f.kgco2e / 1000, 6) as tco2e,
  round(e.qty * coalesce(f.co2, 0) * g.co2 / 1000, 6) as tco2e_co2,
  round(e.qty * (coalesce(f.ch4_fossil, 0) * g.ch4_fossil + coalesce(f.ch4, 0) * g.ch4) / 1000, 6) as tco2e_ch4,
  round(e.qty * coalesce(f.n2o, 0) * g.n2o / 1000, 6) as tco2e_n2o,
  round(e.qty * (coalesce(f.hfc, 0) + coalesce(f.pfc, 0)) / 1000, 6) as tco2e_fgas
from public.tx_${k}_entry e
join public.mt_${k}_activity a on a.id = e.activity_id
join public.mt_${k}_ef f on f.id = e.ef_id
join public.mt_${k}_scope s on s.code = f.scope_code
join public.mt_${k}_gwp g on g.code = e.gwp_code;

-- รวมรายเดือนต่อ Scope (Dashboard)
create or replace view public.v_${k}_month with (security_invoker = true) as
select month, scope, round(sum(tco2e), 6) as tco2e, count(*) as entries
from public.v_${k}_entry
group by month, scope;
`;
}

export function actSql(activity, { audit = true } = {}) {
  if (!ACTIVITIES.includes(activity)) throw new Error(`unknown activity ${activity}`);
  const k = activity.replace(/[^a-z0-9]/g, '');
  const rls = (t) => `alter table public.${t} enable row level security;`;
  const core = `-- ===== ${activity}: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_${k}_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_${k}_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_${k}_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_${k}_team add column if not exists department text;
alter table public.mt_${k}_team
  drop constraint if exists mt_${k}_team_role_check,
  add constraint mt_${k}_team_role_check check (role in ('admin', 'chairman', 'vice', 'auditor', 'owner', 'member')),
  drop constraint if exists mt_${k}_team_member_has_dept,
  add constraint mt_${k}_team_member_has_dept check ((role = 'member') = (department is not null)),
  drop constraint if exists mt_${k}_team_unique,
  add constraint mt_${k}_team_unique unique nulls not distinct (year, employee_id, role, team, area_id, department);
create index if not exists mt_${k}_team_lookup on public.mt_${k}_team (year, employee_id);
create unique index if not exists mt_${k}_team_one_owner on public.mt_${k}_team (year, area_id) where role = 'owner';

create table if not exists public.mt_${k}_setting (
  key text primary key,
  value text not null
);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_${k} · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_${k}', 'img_${k}', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;
`;
  const auditPart = `
-- ===== ${activity}: checklist audit =====

create table if not exists public.mt_${k}_area (
  id bigint generated by default as identity primary key,
  code text not null unique,                              -- เช่น A01
  area_type text not null check (area_type in ('โรงงาน', 'สำนักงาน')),
  name text not null,
  section text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- เจ้าของพื้นที่อยู่ใน mt_${k}_team (role owner) ผูก area_id กับพื้นที่ที่นี่
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'mt_${k}_team_area_fk') then
    alter table public.mt_${k}_team add constraint mt_${k}_team_area_fk foreign key (area_id) references public.mt_${k}_area (id) on delete cascade;
  end if;
end $$;

-- หัวข้อตรวจรายปี (5S: 25 ข้อ, s_group 1–5)
create table if not exists public.mt_${k}_checklist (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  item_no integer not null check (item_no between 1 and 200),
  s_group integer not null check (s_group between 1 and 20),
  title text not null,
  score_max integer not null default 5 check (score_max > 0),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (year, item_no)
);

-- แผนตรวจ Committee: พื้นที่ × เดือน × สัปดาห์ (W1 = 1–7, W2 = 8–14, W3 = 15–21, W4 = 22–สิ้นเดือน)
create table if not exists public.mt_${k}_audit_plan (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  area_id bigint not null references public.mt_${k}_area (id) on delete cascade,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 4),
  round integer check (round between 1 and 6),
  team text check (team ~ '^[A-Z]$'),
  created_at timestamptz not null default now(),
  unique (year, area_id, month, week)
);

insert into public.mt_${k}_setting (key, value) values
  ('pass_percent', '80'),                -- ผ่านเมื่อ % ≥ 80
  ('issue_score', '3'),                  -- Committee: ข้อที่ได้ ≤ 3 ต้องเปิด Issue
  ('issue_due_days_before_next', '10'),  -- แก้ให้เสร็จก่อนตรวจรอบถัดไป 10 วัน
  ('issue_photo_max', '1'),              -- รูปปัญหา 16:9 1 รูป
  ('self_audit_due_day', '10')           -- Self Audit ภายในวันที่ 10 ของเดือน
on conflict (key) do nothing;

create table if not exists public.tx_${k}_audit (
  id bigint generated by default as identity primary key,
  audit_no text not null unique,                          -- C|S-<area>-<ddMMyy>-<seq> เช่น C-A01-040926-01
  year integer not null check (year between 2000 and 2100),
  audit_type text not null check (audit_type in ('SELF', 'COMMITTEE')),
  area_id bigint not null references public.mt_${k}_area (id),
  plan_id bigint references public.mt_${k}_audit_plan (id) on delete set null,
  team text,
  auditors text[] not null default '{}',                  -- ผู้ตรวจที่ไปตรวจจริง (employee_id)
  receivers text[] not null default '{}',                 -- ผู้รับตรวจในพื้นที่ (employee_id)
  audited_at timestamptz not null,
  total_score numeric(8, 2) not null default 0,
  percent_score numeric(5, 2) not null default 0,
  result text check (result in ('PASS', 'NEED_IMPROVE')),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'COMPLETED')),
  created_by text,
  created_at timestamptz not null default now()
);
create index if not exists tx_${k}_audit_lookup on public.tx_${k}_audit (year, area_id, audited_at);

create table if not exists public.tx_${k}_audit_score (
  audit_id bigint not null references public.tx_${k}_audit (id) on delete cascade,
  checklist_id bigint not null references public.mt_${k}_checklist (id),
  score numeric(5, 2) not null check (score >= 0),       -- 0 = Issue เดิมไม่มี Action
  primary key (audit_id, checklist_id)
);

create table if not exists public.tx_${k}_issue (
  id bigint generated by default as identity primary key,
  issue_no text not null unique,                          -- ISS0001
  audit_id bigint not null references public.tx_${k}_audit (id) on delete cascade,
  area_id bigint not null references public.mt_${k}_area (id),
  checklist_id bigint not null references public.mt_${k}_checklist (id),
  score numeric(5, 2) not null,
  description text not null,
  photo_before text[] not null default '{}',              -- ลิงก์รูปปัญหา (16:9)
  photo_after text[] not null default '{}',               -- ลิงก์รูปหลังแก้
  issue_date date not null,
  responsible_id text,
  due_date date,                                          -- null = รอกำหนดรอบถัดไป
  action_description text,
  action_date date,
  status text not null default 'OPEN' check (status in ('OPEN', 'ON_PLAN', 'WAIT_VERIFY', 'OVERDUE', 'CLOSED')),
  verify_audit_no text,                                   -- ใบตรวจรอบถัดไปที่ยืนยันผล (ข้อมูลเดิมบางใบไม่มีในระบบ จึงเก็บเป็นเลข)
  final_score numeric(5, 2),
  closed_by text,
  closed_at date
);
create index if not exists tx_${k}_issue_area on public.tx_${k}_issue (area_id, status);

-- % ของแต่ละหมวดต่อใบตรวจ (Summary / Ranking) · security_invoker = ใช้สิทธิ์ของคนเรียก ไม่ข้าม RLS
create or replace view public.v_${k}_audit_group with (security_invoker = true) as
select s.audit_id, c.s_group,
  sum(s.score) as score,
  sum(c.score_max) as score_max,
  round(sum(s.score) * 100.0 / nullif(sum(c.score_max), 0), 2) as percent
from public.tx_${k}_audit_score s
join public.mt_${k}_checklist c on c.id = s.checklist_id
group by s.audit_id, c.s_group;
`;
  const extra = activity === 'cfo';
  const tables = [`mt_${k}_team`, `mt_${k}_setting`, `mt_${k}_task`]
    .concat(extra ? [`mt_${k}_scope`, `mt_${k}_gwp`, `mt_${k}_ef`, `mt_${k}_activity`, `tx_${k}_entry`] : [], audit
    ? [`mt_${k}_area`, `mt_${k}_checklist`, `mt_${k}_audit_plan`, `tx_${k}_audit`, `tx_${k}_audit_score`, `tx_${k}_issue`]
    : []);
  return `-- กิจกรรม ${activity} — รันใน **Tx Data** (รันซ้ำได้) · สร้างจาก scripts/act-sql.js ห้ามแก้มือ
-- spec: docs/specs/act-5s.md · ทดสอบ: npm run test:act

${core}${taskTableSql(activity, k)}${extra ? cfoSql(k) : ''}${audit ? auditPart : ''}
-- server ใช้ service key ซึ่งข้าม RLS ได้ เปิด RLS ไว้กันการเข้าถึงด้วย anon key
${tables.map(rls).join('\n')}

notify pgrst, 'reload schema';
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const activity = process.argv[2];
  if (!activity) {
    console.error('usage: node scripts/act-sql.js <activity> [--no-audit | --add-task]');
    process.exit(1);
  }
  const addTask = process.argv.includes('--add-task');
  const out = path.join(ROOT, 'db', 'act', `${activity}${addTask ? '_task' : ''}.sql`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, addTask ? actTaskSql(activity) : actSql(activity, { audit: !process.argv.includes('--no-audit') }));
  console.log(`wrote ${path.relative(ROOT, out)}`);
}
