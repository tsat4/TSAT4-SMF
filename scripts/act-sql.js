// SQL for one activity in Tx Data, from one template so every activity has the same shape.
//   node scripts/act-sql.js 5s            -> db/act/5s.sql      (plan + team + checklist audit tables)
//   node scripts/act-sql.js kaizen --plan -> db/act/kaizen.sql  (plan + team only, no audit tables)
// Table names: mt_<key>_* (setting) / tx_<key>_* (transaction), key = activity id without symbols (e-day -> eday).
// Keep server/modules/act/common.js tablesOf() in step with the names here.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ACTIVITIES = ['100p', '5s', 'cfo', 'e-day', 'kaizen', 'lean', 'qcc', 'safety', 'smf'];

export function actSql(activity, { audit = true } = {}) {
  if (!ACTIVITIES.includes(activity)) throw new Error(`unknown activity ${activity}`);
  const k = activity.replace(/[^a-z0-9]/g, '');
  const rls = (t) => `alter table public.${t} enable row level security;`;
  const core = `-- ===== ${activity}: team, settings, yearly plan (Gantt) =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting, chairman = หัวหน้าทีมตรวจ, auditor = ผู้ตรวจในทีม A–Z,
-- owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่ 1 คนดูแลได้หลายพื้นที่
create table if not exists public.mt_${k}_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null constraint mt_${k}_team_role_check check (role in ('admin', 'chairman', 'auditor', 'owner')),
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_${k}_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_${k}_team_owner_has_area check ((role = 'owner') = (area_id is not null)),
  constraint mt_${k}_team_unique unique nulls not distinct (year, employee_id, role, team, area_id)
);
create index if not exists mt_${k}_team_lookup on public.mt_${k}_team (year, employee_id);
create unique index if not exists mt_${k}_team_one_owner on public.mt_${k}_team (year, area_id) where role = 'owner';

create table if not exists public.mt_${k}_setting (
  key text primary key,
  value text not null
);

-- แผนประจำปีแบบ Gantt (รายการชื่อเดียวกันอยู่แถวเดียวกัน) และปฏิทินรวม
create table if not exists public.mt_${k}_plan (
  id bigint generated by default as identity primary key,
  title text not null,
  detail text,
  start_date date not null,
  end_date date not null,
  responsible text,
  status text not null default 'planned' check (status in ('planned', 'done', 'cancelled')),
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_${k}_plan_dates check (end_date >= start_date)
);
create index if not exists mt_${k}_plan_dates on public.mt_${k}_plan (start_date, end_date);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_${k} · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_${k}', 'img_${k}', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;
`;
  const auditPart = `
-- ===== ${activity}: checklist audit =====

create table if not exists public.mt_${k}_area (
  id bigint generated by default as identity primary key,
  code text not null unique,                              -- เช่น A01
  area_type text not null check (area_type in ('โรงงาน', 'สำนักงาน')),
  name text not null,
  section text,
  status text not null default 'Active' check (status in ('Active', 'Inactive'))
);

-- เจ้าของพื้นที่อยู่ใน mt_${k}_team (role owner) ผูก area_id กับพื้นที่ที่นี่
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'mt_${k}_team_area_fk') then
    alter table public.mt_${k}_team add constraint mt_${k}_team_area_fk foreign key (area_id) references public.mt_${k}_area (id) on delete cascade;
  end if;
end $$;

-- หัวข้อตรวจรายปี (5S: 25 ข้อ, s_group 1–5)
create table if not exists public.mt_${k}_checklist (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  item_no integer not null check (item_no between 1 and 200),
  s_group integer not null check (s_group between 1 and 20),
  title text not null,
  score_max integer not null default 5 check (score_max > 0),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (year, item_no)
);

-- แผนตรวจ Committee: พื้นที่ × เดือน × สัปดาห์ (W1 = 1–7, W2 = 8–14, W3 = 15–21, W4 = 22–สิ้นเดือน)
create table if not exists public.mt_${k}_audit_plan (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  area_id bigint not null references public.mt_${k}_area (id) on delete cascade,
  month integer not null check (month between 1 and 12),
  week integer not null check (week between 1 and 4),
  round integer check (round between 1 and 6),
  team text check (team ~ '^[A-Z]$'),
  created_at timestamptz not null default now(),
  unique (year, area_id, month, week)
);

insert into public.mt_${k}_setting (key, value) values
  ('pass_percent', '80'),                -- ผ่านเมื่อ % ≥ 80
  ('issue_score', '3'),                  -- Committee: ข้อที่ได้ ≤ 3 ต้องเปิด Issue
  ('issue_due_days_before_next', '10'),  -- แก้ให้เสร็จก่อนตรวจรอบถัดไป 10 วัน
  ('issue_photo_max', '1'),              -- รูปปัญหา 16:9 1 รูป
  ('self_audit_due_day', '10')           -- Self Audit ภายในวันที่ 10 ของเดือน
on conflict (key) do nothing;

create table if not exists public.tx_${k}_audit (
  id bigint generated by default as identity primary key,
  audit_no text not null unique,                          -- C|S-<area>-<ddMMyy>-<seq> เช่น C-A01-040926-01
  year integer not null check (year between 2000 and 2100),
  audit_type text not null check (audit_type in ('SELF', 'COMMITTEE')),
  area_id bigint not null references public.mt_${k}_area (id),
  plan_id bigint references public.mt_${k}_audit_plan (id) on delete set null,
  team text,
  auditors text[] not null default '{}',                  -- ผู้ตรวจที่ไปตรวจจริง (employee_id)
  receivers text[] not null default '{}',                 -- ผู้รับตรวจในพื้นที่ (employee_id)
  audited_at timestamptz not null,
  total_score numeric(8, 2) not null default 0,
  percent_score numeric(5, 2) not null default 0,
  result text check (result in ('PASS', 'NEED_IMPROVE')),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'COMPLETED')),
  created_by text,
  created_at timestamptz not null default now()
);
create index if not exists tx_${k}_audit_lookup on public.tx_${k}_audit (year, area_id, audited_at);

create table if not exists public.tx_${k}_audit_score (
  audit_id bigint not null references public.tx_${k}_audit (id) on delete cascade,
  checklist_id bigint not null references public.mt_${k}_checklist (id),
  score numeric(5, 2) not null check (score >= 0),       -- 0 = Issue เดิมไม่มี Action
  primary key (audit_id, checklist_id)
);

create table if not exists public.tx_${k}_issue (
  id bigint generated by default as identity primary key,
  issue_no text not null unique,                          -- ISS0001
  audit_id bigint not null references public.tx_${k}_audit (id) on delete cascade,
  area_id bigint not null references public.mt_${k}_area (id),
  checklist_id bigint not null references public.mt_${k}_checklist (id),
  score numeric(5, 2) not null,
  description text not null,
  photo_before text[] not null default '{}',              -- ลิงก์รูปปัญหา (16:9)
  photo_after text[] not null default '{}',               -- ลิงก์รูปหลังแก้
  issue_date date not null,
  responsible_id text,
  due_date date,                                          -- null = รอกำหนดรอบถัดไป
  action_description text,
  action_date date,
  status text not null default 'OPEN' check (status in ('OPEN', 'ON_PLAN', 'WAIT_VERIFY', 'OVERDUE', 'CLOSED')),
  verify_audit_no text,                                   -- ใบตรวจรอบถัดไปที่ยืนยันผล (ข้อมูลเดิมบางใบไม่มีในระบบ จึงเก็บเป็นเลข)
  final_score numeric(5, 2),
  closed_by text,
  closed_at date
);
create index if not exists tx_${k}_issue_area on public.tx_${k}_issue (area_id, status);

-- % ของแต่ละหมวดต่อใบตรวจ (Summary / Ranking) · security_invoker = ใช้สิทธิ์ของคนเรียก ไม่ข้าม RLS
create or replace view public.v_${k}_audit_group with (security_invoker = true) as
select s.audit_id, c.s_group,
  sum(s.score) as score,
  sum(c.score_max) as score_max,
  round(sum(s.score) * 100.0 / nullif(sum(c.score_max), 0), 2) as percent
from public.tx_${k}_audit_score s
join public.mt_${k}_checklist c on c.id = s.checklist_id
group by s.audit_id, c.s_group;
`;
  const tables = [`mt_${k}_team`, `mt_${k}_setting`, `mt_${k}_plan`].concat(audit
    ? [`mt_${k}_area`, `mt_${k}_checklist`, `mt_${k}_audit_plan`, `tx_${k}_audit`, `tx_${k}_audit_score`, `tx_${k}_issue`]
    : []);
  return `-- กิจกรรม ${activity} — รันใน **Tx Data** (รันซ้ำได้) · สร้างจาก scripts/act-sql.js ห้ามแก้มือ
-- spec: docs/specs/act-5s.md · ทดสอบ: npm run test:act

${core}${audit ? auditPart : ''}
-- server ใช้ service key ซึ่งข้าม RLS ได้ เปิด RLS ไว้กันการเข้าถึงด้วย anon key
${tables.map(rls).join('\n')}

notify pgrst, 'reload schema';
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const activity = process.argv[2];
  if (!activity) {
    console.error('usage: node scripts/act-sql.js <activity> [--plan]');
    process.exit(1);
  }
  const out = path.join(ROOT, 'db', 'act', `${activity}.sql`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, actSql(activity, { audit: !process.argv.includes('--plan') }));
  console.log(`wrote ${path.relative(ROOT, out)}`);
}
